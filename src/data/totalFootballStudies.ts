const theme = (primary: string, secondary: string): CaseStudyTheme => {
  const soft = (hex: string, a: number) => {
    const n = parseInt(hex.slice(1), 16)
    return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`
  }
  return {
    primary,
    secondary,
    primarySoft: soft(primary, 0.14),
    primaryBorder: soft(primary, 0.26),
    secondarySoft: soft(secondary, 0.12),
    secondaryBorder: soft(secondary, 0.24),
  }
}

